"""Synthetic fixture corpora, generated deterministically from a fixed seed.

Three corpora, used by the test suite (acceptance gates 1-3):

* `valid_manifest()` -- realistic, fully-compliant tools that must produce
  ZERO findings against every provider in `providers.DEFAULT_PROVIDER_SET`.
  This is the false-flag-rate control.

* `planted_manifest()` -- one (or more) tool per rule class, each crafted so
  the defect is unambiguous, paired with the rule_id it must trigger. This
  is the detection-rate corpus.

* `per_provider_manifest()` -- a schema that is legal for one provider and
  illegal for a stricter one, to prove a fix does not "land on half its
  class" by over- or under-flagging.

Nothing here is randomized data used for correctness assertions -- the
defect *shapes* are fixed and hand-specified (randomness would make a
"detection failed" result ambiguous: bad luck vs. a real regression). The
`Random(SEED)` instance is used only for cosmetic variation (padding
strings to a target length, picking among synonymous benign values) so the
corpus is still reproducibly "generated by this repo from a fixed seed" per
the spec, not hand-typed data masquerading as a generator.
"""
from __future__ import annotations

import random
from dataclasses import dataclass

SEED = 20260902


@dataclass(frozen=True)
class PlantedDefect:
    rule_id: str
    tool_name: str
    note: str


def _rng() -> random.Random:
    return random.Random(SEED)


def _padded_description(prefix: str, target_len: int, rng: random.Random) -> str:
    filler_words = ["parameter", "value", "field", "note", "detail", "context", "usage"]
    out = prefix
    while len(out) < target_len:
        out += " " + rng.choice(filler_words)
    return out[:target_len] if len(out) > target_len else out


