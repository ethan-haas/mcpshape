# ---------------------------------------------------------------------------
# Planted-defect corpus -- one tool per rule, paired with expected rule_id
# ---------------------------------------------------------------------------


def planted_manifest() -> tuple[dict, list[PlantedDefect]]:
    rng = _rng()
    tools = []
    defects: list[PlantedDefect] = []

    # 1. unsupported-keyword: 'not' is unsupported by openai and google.
    tools.append(
        {
            "name": "kw_violator",
            "description": _padded_description("Uses a keyword some providers reject.", 60, rng),
            "inputSchema": {
                "type": "object",
                "properties": {"x": {"type": "string"}},
                "not": {"type": "null"},
                "additionalProperties": False,
            },
        }
    )
    defects.append(PlantedDefect("unsupported-keyword", "kw_violator", "root 'not' keyword"))

    # 2. nesting-too-deep: 6 levels of nested objects, exceeds openai's cap of 5.
    deep_schema = {"type": "string"}
    for level in range(6, 0, -1):
        deep_schema = {
            "type": "object",
            "properties": {f"level{level}": deep_schema},
            "additionalProperties": False,
        }
    tools.append(
        {
            "name": "deep_nester",
            "description": _padded_description("Nests objects far deeper than providers allow.", 60, rng),
            "inputSchema": deep_schema,
        }
    )
    defects.append(PlantedDefect("nesting-too-deep", "deep_nester", "6 levels of object nesting"))

    # 3a. name-pattern: invalid characters.
    tools.append(
        {
            "name": "bad name!",
            "description": _padded_description("Tool name has a space and punctuation.", 60, rng),
            "inputSchema": {
                "type": "object",
                "properties": {"x": {"type": "string"}},
                "additionalProperties": False,
            },
        }
    )
    defects.append(PlantedDefect("name-pattern", "bad name!", "space + punctuation in name"))

    # 3b. name-pattern: too long for openai/google (max 64).
    long_name = "a_very_long_tool_name_" + ("x" * 60)
    tools.append(
        {
            "name": long_name,
            "description": _padded_description("Tool name is far too long.", 60, rng),
            "inputSchema": {
                "type": "object",
                "properties": {"x": {"type": "string"}},
                "additionalProperties": False,
            },
        }
    )
    defects.append(PlantedDefect("name-pattern", long_name, "name length exceeds provider caps"))

    # 4. description-too-long: 2000 chars, exceeds openai/google's 1024 cap.
    tools.append(
        {
            "name": "verbose_tool",
            "description": _padded_description("Extremely verbose tool.", 2000, rng),
            "inputSchema": {
                "type": "object",
                "properties": {"x": {"type": "string"}},
                "additionalProperties": False,
            },
        }
    )
    defects.append(PlantedDefect("description-too-long", "verbose_tool", "2000-char description"))

    # 5. required-missing-property.
    tools.append(
        {
            "name": "unsatisfiable_required",
            "description": _padded_description("Requires a property that does not exist.", 60, rng),
            "inputSchema": {
                "type": "object",
                "properties": {"x": {"type": "string"}},
                "required": ["x", "y_does_not_exist"],
                "additionalProperties": False,
            },
        }
    )
    defects.append(
        PlantedDefect("required-missing-property", "unsatisfiable_required", "'y_does_not_exist' not in properties")
    )

    # 6. additional-properties-open: object schema with additionalProperties unset.
    tools.append(
        {
            "name": "open_object",
            "description": _padded_description("Object schema never closes extra args.", 60, rng),
            "inputSchema": {
                "type": "object",
                "properties": {"x": {"type": "string"}},
                # additionalProperties intentionally omitted
            },
        }
    )
    defects.append(PlantedDefect("additional-properties-open", "open_object", "additionalProperties unset"))

    # 7. duplicate-tool-name: planted as a pair, appended after the loop below.
    dup_tool = {
        "name": "duplicate_tool",
        "description": _padded_description("First copy of a duplicated tool.", 60, rng),
        "inputSchema": {
            "type": "object",
            "properties": {"x": {"type": "string"}},
            "additionalProperties": False,
        },
    }
    tools.append(dup_tool)
    tools.append(dict(dup_tool))  # exact duplicate name
    defects.append(PlantedDefect("duplicate-tool-name", "duplicate_tool", "same name appears twice"))

    # 8a. empty-enum-or-bad-default: empty enum.
    tools.append(
        {
            "name": "empty_enum_tool",
            "description": _padded_description("Has an enum with no allowed values.", 60, rng),
            "inputSchema": {
                "type": "object",
                "properties": {"mode": {"type": "string", "enum": []}},
                "additionalProperties": False,
            },
        }
    )
    defects.append(PlantedDefect("empty-enum-or-bad-default", "empty_enum_tool", "enum: []"))

    # 8b. empty-enum-or-bad-default: default violates local schema (5 < minimum 10).
    tools.append(
        {
            "name": "bad_default_tool",
            "description": _padded_description("Default value violates its own bounds.", 60, rng),
            "inputSchema": {
                "type": "object",
                "properties": {
                    "count": {"type": "integer", "minimum": 10, "default": 5},
                },
                "additionalProperties": False,
            },
        }
    )
    defects.append(PlantedDefect("empty-enum-or-bad-default", "bad_default_tool", "default 5 < minimum 10"))

    # 9a. missing-input-schema: inputSchema absent entirely.
    tools.append(
        {
            "name": "no_schema_tool",
            "description": _padded_description("Has no inputSchema at all.", 60, rng),
        }
    )
    defects.append(PlantedDefect("missing-input-schema", "no_schema_tool", "inputSchema absent"))

    # 9b. missing-input-schema: inputSchema.type is not 'object'.
    tools.append(
        {
            "name": "wrong_type_schema_tool",
            "description": _padded_description("inputSchema.type is 'string', not 'object'.", 60, rng),
            "inputSchema": {"type": "string"},
        }
    )
    defects.append(PlantedDefect("missing-input-schema", "wrong_type_schema_tool", "inputSchema.type == 'string'"))

    return {"tools": tools}, defects


# ---------------------------------------------------------------------------
# Per-provider control: legal for one provider, illegal for a stricter one.
# ---------------------------------------------------------------------------


def per_provider_manifest() -> tuple[dict, dict]:
    """A schema nested 5 levels deep.

    openai's max_nesting_depth is 5 (legal, exactly at the cap) and
    anthropic's is 8 (legal). google's is 4 (illegal -- exceeds by one
    level). Used to prove a stricter-provider finding does not leak into a
    more permissive provider's report.
    """
    rng = _rng()
    schema = {"type": "string"}
    for level in range(5, 0, -1):
        schema = {
            "type": "object",
            "properties": {f"level{level}": schema},
            "additionalProperties": False,
        }
    tool = {
        "name": "moderately_nested",
        "description": _padded_description("Nested exactly at the openai cap, over google's.", 60, rng),
        "inputSchema": schema,
    }
    manifest = {"tools": [tool]}
    expectation = {
        "tool_name": "moderately_nested",
        "rule_id": "nesting-too-deep",
        "legal_provider": "openai",
        "illegal_provider": "google",
    }
    return manifest, expectation
